// Package selfhelp — небольшая библиотека самопомощи.
// Пока специалист не ответил, заявителю показываются короткие безопасные
// материалы по предсказанной категории. Это не заменяет специалиста и не
// является клинической рекомендацией — только первая поддержка «здесь и сейчас».
package selfhelp

// Material — единица библиотеки.
//   Kind: "step" (что можно сделать), "exercise" (упражнение), "read" (полезно знать).
type Material struct {
	Title string `json:"title"`
	Kind  string `json:"kind"`
	Body  string `json:"body"`
	URL   string `json:"url,omitempty"`
}

// general показывается всегда, независимо от категории.
func general() []Material {
	return []Material{
		{
			Kind:  "exercise",
			Title: "Дыхание «по квадрату», чтобы успокоиться",
			Body:  "Если тревожно прямо сейчас: вдох на 4 счёта — задержка на 4 — выдох на 4 — пауза на 4. Повтори 4–5 кругов. Это помогает телу выйти из режима паники и мыслить яснее.",
		},
		{
			Kind:  "step",
			Title: "Найди взрослого, которому доверяешь",
			Body:  "Подумай, кому из взрослых ты можешь рассказать: родитель, классный руководитель, школьный психолог, тренер, родственник. Не обязательно всё и сразу — можно начать с фразы «мне нужно с тобой поговорить, мне тяжело».",
		},
	}
}

// byCategory — материалы по слагу категории.
func byCategory(slug string) []Material {
	switch slug {
	case "bullying":
		return []Material{
			{Kind: "read", Title: "Травля — это не твоя вина", Body: "Тебя травят не потому, что с тобой «что-то не так». Ответственность всегда на том, кто причиняет вред. Ты имеешь право чувствовать себя в безопасности в школе."},
			{Kind: "step", Title: "Сохраняй доказательства", Body: "Если есть сообщения, записки, свидетели — сохрани их (скриншоты, фото). Это поможет взрослым разобраться и защитить тебя."},
			{Kind: "step", Title: "Старайся не оставаться один на один", Body: "Держись рядом с теми, с кем спокойно: друзья, места, где есть взрослые. Это снижает риск и придаёт сил."},
		}
	case "cyberbullying":
		return []Material{
			{Kind: "step", Title: "Не отвечай, но сохрани", Body: "Не вступай в переписку с обидчиком — это часто подпитывает травлю. Сделай скриншоты сообщений: они пригодятся, чтобы пожаловаться и рассказать взрослым."},
			{Kind: "step", Title: "Заблокируй и пожалуйся", Body: "В соцсети или мессенджере можно заблокировать человека и отправить жалобу на его сообщения. Проверь настройки приватности: кто может тебе писать и видеть твой профиль."},
			{Kind: "read", Title: "Цифровой след обидчика остаётся", Body: "Онлайн-агрессия оставляет следы, и её можно остановить. Ты не обязан справляться в одиночку."},
		}
	case "classmates":
		return []Material{
			{Kind: "exercise", Title: "Я-сообщения вместо обвинений", Body: "Фраза «ты вечно...» вызывает защиту и ссору. Попробуй: «Мне неприятно, когда..., и я хочу...». Так проще быть услышанным и не разжечь конфликт."},
			{Kind: "step", Title: "Возьми паузу", Body: "Если эмоции зашкаливают — не решай в моменте. Отойди, выдохни, вернись к разговору позже, когда станет спокойнее."},
		}
	case "pressure":
		return []Material{
			{Kind: "read", Title: "Угрозы и давление — это серьёзно", Body: "Никто не имеет права угрожать тебе или заставлять что-то делать силой. Если есть угроза твоей безопасности — это повод обратиться к взрослым и, при необходимости, в полицию."},
			{Kind: "step", Title: "Обозначь границу и уйди", Body: "Коротко и твёрдо: «Нет». Не оправдывайся и не спорь — выйди из ситуации и окажись рядом с людьми, где безопаснее."},
			{Kind: "step", Title: "Расскажи взрослому как можно скорее", Body: "Давление редко проходит само. Чем раньше об этом узнает взрослый, которому ты доверяешь, тем быстрее тебя смогут защитить."},
		}
	case "teacher":
		return []Material{
			{Kind: "step", Title: "Спокойный разговор наедине", Body: "Иногда конфликт с учителем можно смягчить коротким разговором без класса: «Мне важно понять, что я могу сделать по-другому». Если страшно — попроси поддержки у родителя или другого взрослого."},
			{Kind: "read", Title: "У тебя есть право на уважение", Body: "Оценки касаются работы, а не твоей личности. Унижение недопустимо. Если чувствуешь несправедливость — это можно обсудить с родителем, соцпедагогом или администрацией школы."},
		}
	case "parents":
		return []Material{
			{Kind: "exercise", Title: "Выбери спокойный момент для разговора", Body: "Тяжёлые темы лучше обсуждать не на пике ссоры. Начни с малого: «Мне важно, чтобы ты меня выслушал(а), можем поговорить?»."},
			{Kind: "step", Title: "Нейтральный взрослый-посредник", Body: "Если разговор дома заходит в тупик, помочь может нейтральный взрослый — родственник, школьный психолог или соцпедагог. Это нормально — просить о посредничестве."},
		}
	case "legal":
		return []Material{
			{Kind: "read", Title: "У тебя есть права", Body: "Даже будучи школьником, ты имеешь права, и их можно защищать. Если ситуация юридическая — специалист-юрист поможет разобраться, что делать по шагам."},
			{Kind: "step", Title: "Зафиксируй факты", Body: "Запиши, что и когда произошло, сохрани документы, сообщения, имена свидетелей. Это очень поможет при разборе ситуации."},
		}
	}
	return nil
}

// For возвращает материалы для категории плюс общие. Всегда возвращает непустой список.
func For(slug string) []Material {
	out := byCategory(slug)
	out = append(out, general()...)
	return out
}
